"""Draws the devices icon (Spotify's: a phone behind a speaker) as LVGL alpha-only images, one size per board.

Usage: python3 tools/make_icons.py   (needs Pillow; run from the project folder). Writes src/icons/icon_devices.c.
The icons are drawn 8x larger and scaled down, for smooth edges. LVGL colours them like text (img_recolor).
"""
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "icons", "icon_devices.c")
SS = 8  # supersampling
# (C name, height in px, board guard): about the height of the symbol glyphs in FONT_UI_SMALL.
SIZES = [("icon_devices_14", 13, "!defined(BOARD_ESP32_4848S040)"), ("icon_devices_22", 20, "defined(BOARD_ESP32_4848S040)")]


def draw(height):
    # Spotify's devices icon, traced on a 122 x 100 unit grid: a phone outline whose right side is hidden
    # behind a speaker outline, the phone's home button below it, and the speaker's tweeter and woofer.
    width = round(height * 1.22)
    W, H = width * SS, height * SS
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    u = H / 100.0
    stroke = max(9 * u, 1.25 * SS)  # keeps the outlines visible at 13 px

    def box(x0, y0, x1, y1):
        return [x0 * u, y0 * u, x1 * u - 1, y1 * u - 1]

    # Phone: outline, cut off on the right where it goes behind the speaker.
    d.rounded_rectangle(box(0, 2, 40, 68), radius=10 * u, outline=255, width=round(stroke))
    d.rectangle(box(31, 0, 44, 100), fill=0)
    d.ellipse(box(17.5, 86.5, 28.5, 97.5), fill=255)

    # Speaker: outline with a filled tweeter and woofer.
    d.rounded_rectangle(box(44, 2, 120, 98), radius=12 * u, outline=255, width=round(stroke))
    d.ellipse(box(82 - 6, 26 - 6, 82 + 6, 26 + 6), fill=255)
    d.ellipse(box(82 - 14, 62 - 14, 82 + 14, 62 + 14), fill=255)
    return img.resize((width, height), Image.LANCZOS)


def main():
    parts = ["// Generated by tools/make_icons.py: the devices icon, a speaker next to a phone.\n",
             "#include <lvgl.h>\n"]
    for name, height, guard in SIZES:
        img = draw(height)
        data = list(img.getdata())
        rows = []
        for y in range(img.height):
            row = data[y * img.width:(y + 1) * img.width]
            rows.append("    " + ", ".join(f"0x{v:02x}" for v in row) + ",")
        parts.append(f"""
#if {guard}
static const uint8_t {name}_map[] = {{
{chr(10).join(rows)}
}};

const lv_img_dsc_t {name} = {{
    .header = {{.cf = LV_IMG_CF_ALPHA_8BIT, .always_zero = 0, .reserved = 0, .w = {img.width}, .h = {img.height}}},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
}};
#endif
""")
    with open(OUT, "w") as f:
        f.write("".join(parts))
    print("Wrote", OUT)


if __name__ == "__main__":
    main()
